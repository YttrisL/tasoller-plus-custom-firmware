/* Initialised data, copied to RAM 0x20000000 at start-up (kept as source).
 * Other code reaches these variables by their RAM address (see src/state.h), so the layout
 * is the official one: the offsets are checked below. The parts called unnamed_* are variables
 * with a value other than zero at start that are not described here. */

#include <stddef.h>
#include <stdint.h>
#include "strings.h"

/* state.h is not included: its macros have the names of the members below. */
uint32_t hook_noop(void);

typedef struct {
    uint32_t system_core_clock[1];  /* Hz, updated by SystemCoreClockUpdate */
    uint32_t cycles_per_us[1];
    uint32_t pll_clock[1];
    uint32_t clock_sources[8];  /* frequency of each source of HCLK */
    uint8_t usb_default_device_descriptor[18];  /* device descriptor before a personality is chosen */
    uint8_t unnamed_03e[2];
    uint8_t usb_hid_report_vendor[68];  /* vendor HID report descriptors (the first, 0x1f bytes, is the one in use) */
    uint8_t usb_bos_descriptor[60];  /* BOS: WebUSB and Microsoft OS 2.0 platform capabilities */
    uint8_t usb_ms_os_descriptor[178];  /* Microsoft OS 2.0 descriptor set (WinUSB for interface 0) */
    uint8_t unnamed_172[2];
    uint8_t usb_webusb_url_descriptor[16];  /* unused: the WebUSB landing page is now in flash (usb_device.c); the slot keeps the RAM layout */
    uint8_t usb_language_descriptor[4];  /* string 0: English (US) */
    uint32_t usb_interface_name[32];  /* string 4: the name of the HID interfaces */
    uint32_t usb_string_table[122];  /* pointers to the string descriptors */
    uint8_t unnamed_3f0[532];
    uint32_t usbd_info[7];  /* descriptors for the USB library */
    uint8_t unnamed_620[44];
    uint32_t default_hooks[8];  /* hooks of the personalities, set by personality_select */
    uint8_t unnamed_66c[28];
    uint8_t aes_default_key[16];  /* the key every device starts with */
    uint8_t unnamed_698[48];
    uint32_t touch_ring_pointers[12];  /* read, write and data pointers of the four rings (no longer used) */
    uint8_t unnamed_6f8[12];
    uint8_t usb_keyboard_report_descriptor[65];  /* HID report descriptor of the keyboard */
    uint8_t unnamed_745[3];
    uint8_t usb_keyboard_config_descriptor[98];  /* configuration descriptor of the keyboard */
    uint8_t unnamed_7aa[2];
    uint8_t usb_keyboard_device_descriptor[18];  /* device descriptor of the keyboard */
    uint8_t unnamed_7be[1598];
    uint8_t usb_winusb_config_descriptor[96];  /* configuration descriptor of the WinUSB mode */
    uint8_t usb_winusb_device_descriptor[18];  /* device descriptor of the WinUSB mode */
    uint8_t unnamed_e6e[6];
    uint32_t unused_pad_table[32];  /* was the table of pad accessors, now in personality.c */
    uint8_t unnamed_ef4[12];
    uint32_t air_led_pins[18];  /* six pins: port, bit mask, number */
    uint8_t unnamed_f48[24];
    uint32_t input_pins[24];  /* six air receivers, the service button and the test button */
    uint8_t unnamed_fc0[1];
    uint8_t air_input_map[6];  /* pin of the receiver for each air LED */
    uint8_t unnamed_fc7[93];
} ram_init_t;

